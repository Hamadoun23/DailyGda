window.GDA_I18N = GDA_I18N;

function gdaUiLang() {
  const v = localStorage.getItem(GDA_UI_LANG_KEY);
  return v === 'en' ? 'en' : 'fr';
}

function gdaDateLocale() {
  return gdaUiLang() === 'en' ? 'en-GB' : 'fr-FR';
}

function tr(key) {
  const lang = gdaUiLang();
  const t = GDA_I18N[lang]?.[key] ?? GDA_I18N.fr[key];
  return t != null ? t : key;
}

function trTpl(key, vars) {
  let s = tr(key);
  if (vars && typeof vars === 'object') {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.split(`{${k}}`).join(String(v));
    });
  }
  return s;
}

function applyI18nDocument() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = tr(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && 'placeholder' in el) el.placeholder = tr(key);
  });
  document.documentElement.lang = gdaUiLang();
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', tr(key));
  });
  const photoTabKeys = { avant: 'photo.avant', pendant: 'photo.pendant', apres: 'photo.apres', securite: 'photo.securite', qualite: 'photo.qualite' };
  document.querySelectorAll('[data-photo-tab]').forEach(el => {
    const tab = el.getAttribute('data-photo-tab');
    const k = tab ? photoTabKeys[tab] : null;
    if (k) el.textContent = tr(k);
  });
  syncTaskFilterStatusOptions();
  syncReportWeatherOptions();
  syncModalStatusOptions();
}

function syncModalStatusOptions() {
  const sel = document.getElementById('m-status');
  if (!sel) return;
  const map = { non_demarre: 'status.nd', en_cours: 'status.ip', termine: 'status.ok', annule: 'status.cancel' };
  sel.querySelectorAll('option').forEach(opt => {
    const k = map[opt.value];
    if (k) opt.textContent = tr(k);
  });
}

function syncTaskFilterStatusOptions() {
  const sel = document.getElementById('task-filter-status');
  if (!sel) return;
  const map = { '': 'page.tasks.optAllStatus', non_demarre: 'status.nd', en_cours: 'status.ip', termine: 'status.ok', annule: 'status.cancel' };
  sel.querySelectorAll('option').forEach(opt => {
    const k = map[opt.value];
    if (k) opt.textContent = tr(k);
  });
}

function syncReportWeatherOptions() {
  const sel = document.getElementById('r-weather');
  if (!sel) return;
  const keys = ['weather.sun', 'weather.sunWind', 'weather.cloud', 'weather.rain', 'weather.wind', 'weather.storm'];
  let i = 0;
  sel.querySelectorAll('option').forEach(opt => {
    if (keys[i]) opt.textContent = tr(keys[i]);
    i++;
  });
}

function syncUiLangButtons() {
  const fr = document.getElementById('ui-lang-fr');
  const en = document.getElementById('ui-lang-en');
  if (!fr || !en) return;
  const isFr = gdaUiLang() !== 'en';
  fr.classList.toggle('header-lang__btn--on', isFr);
  en.classList.toggle('header-lang__btn--on', !isFr);
}

function setUiLang(lang) {
  localStorage.setItem(GDA_UI_LANG_KEY, lang === 'en' ? 'en' : 'fr');
  document.documentElement.lang = gdaUiLang();
  syncUiLangButtons();
  applyI18nDocument();
  if (typeof window.gdaOnUiLangChange === 'function') {
    window.gdaOnUiLangChange();
  }
}
